"""
Export TFLite model for ESP32-S3 MicroPython deployment.

This generates:
    esp32/
    ├── model.tflite       # The quantized model file
    ├── labels.txt         # Class labels
    ├── main.py            # MicroPython inference script
    ├── boot.py            # MicroPython boot script
    └── config.json        # Model metadata for inference

Usage:
    uv run tinyml-export
"""

from __future__ import annotations

import argparse
import json
import shutil
from pathlib import Path

from tinyml.config import ModelConfig


# ── MicroPython scripts ─────────────────────────────────────────────

BOOT_PY = """\
# boot.py — ESP32-S3 MicroPython boot script
# This runs once on startup before main.py

import gc
import machine

# Set CPU frequency to max for inference speed
machine.freq(240_000_000)

# Free as much memory as possible
gc.collect()
gc.threshold(gc.mem_free() // 4 + gc.mem_alloc())

print(f"[boot] CPU freq: {machine.freq() // 1_000_000} MHz")
print(f"[boot] Free RAM: {gc.mem_free():,} bytes")
"""


def _generate_main_py(config: ModelConfig, labels: list[str]) -> str:
    """Generate the MicroPython main.py for ESP32-S3 inference.

    This script:
    1. Initializes the camera (if available)
    2. Loads the TFLite model
    3. Runs inference in a loop
    4. Reports predictions via serial/LED
    """
    labels_str = json.dumps(labels)

    return f'''\
"""
TinyML Image Classifier — ESP32-S3 MicroPython
================================================
Auto-generated by tinyml-export. Edit config.json to adjust settings.

Hardware requirements:
  - ESP32-S3 with PSRAM (recommended)
  - Camera module (OV2640 or similar) OR pre-loaded test images
  - MicroPython firmware with microlite (TFLite Micro) support

Firmware:
  Use micropython-esp32-s3 with microlite support. See README.md for
  instructions on flashing the firmware.
"""

import gc
import json
import time

# ── Try importing camera and ML libraries ───────────────────────
try:
    import camera
    HAS_CAMERA = True
except ImportError:
    HAS_CAMERA = False
    print("[warn] No camera module — will use test image")

try:
    import microlite
    HAS_MICROLITE = True
except ImportError:
    HAS_MICROLITE = False
    print("[warn] No microlite module — install MicroPython with TFLite support")


# ── Configuration ───────────────────────────────────────────────
INPUT_SIZE = {config.input_size}
INPUT_CHANNELS = {config.input_channels}
LABELS = {labels_str}
MODEL_PATH = "model.tflite"
CONFIDENCE_THRESHOLD = 0.6


def init_camera():
    """Initialize the camera module."""
    if not HAS_CAMERA:
        return False
    try:
        camera.init(0, format=camera.JPEG, fb_location=camera.PSRAM)
        camera.framesize(camera.FRAME_96X96)
        camera.quality(10)
        print("[camera] Initialized")
        return True
    except Exception as e:
        print(f"[camera] Init failed: {{e}}")
        return False


def capture_image():
    """Capture an image from the camera and resize to model input."""
    if not HAS_CAMERA:
        return None
    try:
        buf = camera.capture()
        return buf
    except Exception as e:
        print(f"[camera] Capture failed: {{e}}")
        return None


def preprocess_image(img_data):
    """Convert raw image bytes to model input tensor.

    For INT8 quantized models, input range is [-128, 127].
    """
    # This is a simplified preprocessor — real implementation depends
    # on your camera output format and image library availability.
    import array

    # Normalize pixel values: [0, 255] -> [-128, 127] for INT8
    processed = array.array('b', (b - 128 for b in img_data[:INPUT_SIZE * INPUT_SIZE * INPUT_CHANNELS]))
    return processed


def load_model():
    """Load the TFLite model using microlite."""
    if not HAS_MICROLITE:
        print("[error] microlite not available")
        return None

    try:
        with open(MODEL_PATH, "rb") as f:
            model_data = f.read()

        # Allocate tensor arena — adjust size based on your model
        # Typical range: 64KB - 256KB for small image classifiers
        arena_size = 200 * 1024  # 200 KB
        interpreter = microlite.interpreter(model_data, arena_size)
        print(f"[model] Loaded ({{len(model_data):,}} bytes, arena={{arena_size:,}} bytes)")
        return interpreter
    except Exception as e:
        print(f"[model] Load failed: {{e}}")
        return None


def predict(interpreter, input_data):
    """Run inference and return (label, confidence) tuple."""
    input_tensor = interpreter.getInputTensor(0)

    # Copy input data to tensor
    for i in range(len(input_data)):
        input_tensor.setValue(i, input_data[i])

    interpreter.invoke()

    output_tensor = interpreter.getOutputTensor(0)

    # Find the class with highest confidence
    best_idx = 0
    best_val = output_tensor.getValue(0)
    for i in range(1, len(LABELS)):
        val = output_tensor.getValue(i)
        if val > best_val:
            best_val = val
            best_idx = i

    # Convert INT8 output to probability (approximate)
    # Output range is [-128, 127], map to [0, 1]
    confidence = (best_val + 128) / 255.0

    return LABELS[best_idx], confidence


def generate_test_image():
    """Generate a dummy test image for testing without a camera."""
    import array
    # Random-ish test pattern
    size = INPUT_SIZE * INPUT_SIZE * INPUT_CHANNELS
    return array.array('b', ((i * 7 + 13) % 256 - 128 for i in range(size)))


def run_inference_loop(interpreter, use_camera=True):
    """Main inference loop."""
    print()
    print("=" * 50)
    print("  TinyML Image Classifier — Running")
    print(f"  Classes: {{LABELS}}")
    print(f"  Input: {{INPUT_SIZE}}x{{INPUT_SIZE}}x{{INPUT_CHANNELS}}")
    print("=" * 50)
    print()

    while True:
        gc.collect()

        if use_camera and HAS_CAMERA:
            img = capture_image()
            if img is None:
                time.sleep(1)
                continue
            input_data = preprocess_image(img)
        else:
            input_data = generate_test_image()

        t_start = time.ticks_us()
        label, confidence = predict(interpreter, input_data)
        t_elapsed = time.ticks_diff(time.ticks_us(), t_start)

        if confidence >= CONFIDENCE_THRESHOLD:
            print(f"[predict] {{label}} ({{confidence:.1%}}) — {{t_elapsed / 1000:.1f}} ms")
        else:
            print(f"[predict] uncertain (best: {{label}} {{confidence:.1%}}) — {{t_elapsed / 1000:.1f}} ms")

        time.sleep(0.5)  # Adjust inference rate as needed


# ── Entry point ─────────────────────────────────────────────────
def main():
    print()
    print("🧠 TinyML Image Classifier for ESP32-S3")
    print(f"   Free RAM: {{gc.mem_free():,}} bytes")
    print()

    # Initialize camera
    use_camera = init_camera()

    # Load model
    interpreter = load_model()
    if interpreter is None:
        print("[error] Cannot proceed without model")
        return

    # Run inference
    try:
        run_inference_loop(interpreter, use_camera=use_camera)
    except KeyboardInterrupt:
        print("\\n[info] Stopped by user")
    finally:
        if HAS_CAMERA:
            try:
                camera.deinit()
            except Exception:
                pass


main()
'''


def _generate_config_json(config: ModelConfig, labels: list[str]) -> str:
    """Generate config.json metadata for the ESP32 deployment."""
    return json.dumps(
        {
            "model": {
                "file": "model.tflite",
                "input_size": config.input_size,
                "input_channels": config.input_channels,
                "quantized": config.quantize_int8,
                "input_dtype": "int8" if config.quantize_int8 else "float32",
            },
            "labels": labels,
            "inference": {
                "confidence_threshold": 0.6,
                "arena_size_kb": 200,
            },
        },
        indent=2,
    )


def export(config: ModelConfig) -> None:
    """Export all files needed for ESP32-S3 MicroPython deployment."""
    esp32_dir = config.esp32_dir
    esp32_dir.mkdir(parents=True, exist_ok=True)

    # Load labels
    if config.labels_path.exists():
        labels = config.labels_path.read_text().strip().split("\n")
    else:
        labels = [f"class_{i}" for i in range(config.num_classes)]
        print(f"⚠ No labels.txt found — using placeholder labels: {labels}")

    print(f"📦 Exporting to {esp32_dir} ...")

    # 1. Copy TFLite model
    tflite_src = config.tflite_model_path
    tflite_dst = esp32_dir / "model.tflite"
    if tflite_src.exists():
        shutil.copy2(tflite_src, tflite_dst)
        size_kb = tflite_dst.stat().st_size / 1024
        print(f"   ✅ model.tflite ({size_kb:.1f} KB)")
    else:
        print(f"   ❌ TFLite model not found at {tflite_src}")
        print("      Run 'uv run tinyml-convert' first")
        return

    # 2. Write labels.txt
    labels_dst = esp32_dir / "labels.txt"
    labels_dst.write_text("\n".join(labels) + "\n")
    print(f"   ✅ labels.txt ({len(labels)} classes)")

    # 3. Generate boot.py
    boot_dst = esp32_dir / "boot.py"
    boot_dst.write_text(BOOT_PY)
    print("   ✅ boot.py")

    # 4. Generate main.py
    main_dst = esp32_dir / "main.py"
    main_dst.write_text(_generate_main_py(config, labels))
    print("   ✅ main.py")

    # 5. Generate config.json
    config_dst = esp32_dir / "config.json"
    config_dst.write_text(_generate_config_json(config, labels))
    print("   ✅ config.json")

    print(f"\n🎉 Export complete! Files in {esp32_dir}/")
    print("\nTo deploy to your ESP32-S3:")
    print("  1. Flash MicroPython with microlite support")
    print("  2. Copy all files from esp32/ to the ESP32 filesystem:")
    print(f"     mpremote cp {esp32_dir}/* :")
    print("  3. Reset the board — it will start classifying automatically")


def main() -> None:
    parser = argparse.ArgumentParser(description="Export model for ESP32-S3")
    args = parser.parse_args()
    config = ModelConfig()
    export(config)


if __name__ == "__main__":
    main()
